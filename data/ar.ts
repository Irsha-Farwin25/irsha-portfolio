/**
 * The portfolio in Modern Standard Arabic. Each list starts from the English data and overrides
 * only its text, so images, links and ids stay in one place. Anything without an override (new
 * entries, placeholder text) falls back to English.
 */

/** Applies per-id text overrides to an English list. */
function localize<T, K extends keyof T>(items: T[], key: K, overrides: Record<string, Partial<T>>): T[] {
  return items.map((item) => ({ ...item, ...overrides[String(item[key])] }));
}

