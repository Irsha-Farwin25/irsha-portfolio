/** Arabic album titles, dates and photo captions (by album id, then image id). */
function localizeAlbums(
  albums: GalleryAlbum[],
  over: Record<string, { title?: string; date?: string; captions?: Record<string, string> }>,
): GalleryAlbum[] {
  return albums.map((a) => {
    const o = over[a.id];
    if (!o) return a;
    return {
      ...a,
      title: o.title ?? a.title,
      date: o.date ?? a.date,
      images: a.images.map((img) => ({ ...img, caption: o.captions?.[img.id] ?? img.caption })),
    };
  });
}

